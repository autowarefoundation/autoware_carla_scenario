@pytest.fixture(autouse=True)
def _entity_registry_left_as_found() -> Iterator[None]:
    """Put back the entities the registry held when a test started.

    The registry is module-level, and only the runner clears it: an entity a
    test registered (``BaseScenario.register_entity``) would answer to its
    role name in every later test of the process, so an action looking up
    ``"npc1"`` there would find it and drive it (#1592).  The dicts the test
    found are refilled in place, so a test that swapped them with
    ``monkeypatch`` is undone whichever teardown runs first.
    """
    from autoware_carla_scenario.entity import registry

    vehicles, pedestrians = registry._VEHICLES, registry._PEDESTRIANS
    found = (dict(vehicles), dict(pedestrians))
    yield
    vehicles.clear()
    vehicles.update(found[0])
    pedestrians.clear()
    pedestrians.update(found[1])


@pytest.fixture(autouse=True)
def _heavy_metrics_decision_cleared(monkeypatch: pytest.MonkeyPatch) -> None:
    """Start without, and forget, the heavy metrics decision a run left.

    ``apply_metrics`` (every ``scenario`` run) sets
    ``$AUTOWARE_CARLA_SCENARIO_HEAVY_METRICS_DECIDED`` in ``os.environ``,
    which ``CommonRoadSettings`` reads before the user's variable: a run in
    one test would otherwise decide for any later test in the same xdist
    worker.  Set, then removed, so that monkeypatch puts back what was there.
    """
    from autoware_carla_scenario.commonroad.session import HEAVY_METRICS_DECIDED_ENV

    monkeypatch.setenv(HEAVY_METRICS_DECIDED_ENV, "")
    monkeypatch.delenv(HEAVY_METRICS_DECIDED_ENV)


@pytest.fixture(autouse=True)
def _typecheck_mode_left_as_found() -> Iterator[None]:
    """Put back the ``$AUTOWARE_CARLA_SCENARIO_TYPECHECK`` a test found.

    A SLURM task whose batch was checked when it was submitted
    (``slurm.worker.run_task``) sets it to ``off`` in ``os.environ``, for the
    rest of its process.  A test that runs the task in its own process, as
    several do, would otherwise switch the static check off for every later
    test of the same xdist worker: a scenario the check refuses would then be
    built, with no warning (``check_registered_scenario`` returns at
    ``off``).  ``monkeypatch.delenv`` of a variable that is not set records
    nothing to undo, so it does not guard against this.
    """
    import os

    from autoware_carla_scenario.typecheck.mode import TYPECHECK_ENV

    found = os.environ.get(TYPECHECK_ENV)
    yield
    if found is None:
        os.environ.pop(TYPECHECK_ENV, None)
    else:
        os.environ[TYPECHECK_ENV] = found


@pytest.fixture(autouse=True)
def _vehicle_entity_run_state_cleared() -> Iterator[None]:
    """Forget the entry speeds, the warm-up flag and the control holds a test
    left behind.

    All are process-wide and only a ``ScenarioRunner.run_scenario`` clears
    them, at the start and end of its run.  A test that executes a
    ``SpawnAction`` with a speed outside a run holds that speed for its actor
    id, which any later test in the same xdist worker that reads the entry
    speeds or the flag without going through a run would see (#697).
    """
    from autoware_carla_scenario import ego_base_link
    from autoware_carla_scenario.actions.base import reset_control_slots
    from autoware_carla_scenario.entity import vehicle_entity

    yield
    vehicle_entity._set_warmup_done(False)
    vehicle_entity._clear_entry_speeds()
    # As is where an ego that started its scenario outside a run (#739) has
    # its base_link, which the trajectory log and the T4 dataset read.
    ego_base_link.clear_ego_base_link()
    # And who controls which entity: an action a test left running would hold
    # its entity's control domains in the next test.
    reset_control_slots()
